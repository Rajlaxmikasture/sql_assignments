--RETRIVE CUSTOMERS WHO MADE THEIR FIRST PURCHASE IN LAST 6 MONTHS.
SELECT C.CID,C.CNAME ,FIRST_PURCHASE_DATE
 FROM( SELECT CID ,MIN(PURCHASE_DATE) AS FIRST_PURCHASE_DATE
        FROM CUSTOMERS C
        GROUP BY CID )
 JOIN PURCHASE P
ON C.CID = P.CID
WHERE FIRST_PURCHASE_DATE >= ADD_MONTHS(TRUNC(SYSDATE) , -6);

