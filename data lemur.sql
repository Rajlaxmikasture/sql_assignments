--WRITE A QUERY TO CALCULATE THE RUNNING TOTAL OF SALES BY DATE
SELECT
    SALE_DATE,
    AMOUNT,
    SUM(AMOUNT) OVER (
        ORDER BY SALE_DATE
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS RUNNING_TOTAL
FROM SALES
ORDER BY SALE_DATE;

